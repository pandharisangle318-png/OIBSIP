"""Runs the whole test-suite and writes docs/QA_REPORT.md (honest, from real results)."""
from __future__ import annotations

import platform
import sys
import time
import unittest
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


class RecordingResult(unittest.TextTestResult):
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self.rows = []

    def _add(self, test, outcome, note=""):
        doc = (test.shortDescription() or "").strip()
        self.rows.append((test.id().replace("tests.", ""), doc or "Runs without error", outcome, note))

    def addSuccess(self, test):
        super().addSuccess(test); self._add(test, "PASS")

    def addFailure(self, test, err):
        super().addFailure(test, err); self._add(test, "FAIL", str(err[1]).splitlines()[0][:120])

    def addError(self, test, err):
        super().addError(test, err); self._add(test, "FAIL", f"{err[0].__name__}: {str(err[1])[:100]}")

    def addSkip(self, test, reason):
        super().addSkip(test, reason); self._add(test, "NOT RUN", reason)

    def addSubTest(self, test, subtest, err):
        super().addSubTest(test, subtest, err)
        if err is not None:
            self.rows.append((subtest.id().replace("tests.", ""), "subtest", "FAIL", str(err[1]).splitlines()[0][:120]))


def main() -> int:
    suite = unittest.defaultTestLoader.discover(str(ROOT / "tests"), top_level_dir=str(ROOT))
    runner = unittest.TextTestRunner(verbosity=1, resultclass=RecordingResult)
    start = time.time()
    result = runner.run(suite)
    seconds = time.time() - start
    passed = sum(1 for r in result.rows if r[2] == "PASS")
    failed = sum(1 for r in result.rows if r[2] == "FAIL")
    skipped = sum(1 for r in result.rows if r[2] == "NOT RUN")

    lines = [
        "# VYOM - QA Report (generated by tests/run_qa.py)", "",
        f"- Generated: {datetime.now():%Y-%m-%d %H:%M}",
        f"- Python: {platform.python_version()} on {platform.system()} {platform.release()}",
        f"- Result: **{passed} passed, {failed} failed, {skipped} not run** ({seconds:.1f}s)", "",
        "| # | Test name | Expected result | Actual | Notes |", "|---|---|---|---|---|",
    ]
    for i, (name, doc, outcome, note) in enumerate(sorted(result.rows), 1):
        lines.append(f"| {i} | `{name}` | {doc} | **{outcome}** | {note.replace('|', '/')} |")
    lines += [
        "", "## Checks that automated tests cannot prove", "",
        "These need real hardware, accounts or Windows. They are NOT covered by the table above unless it says otherwise.", "",
        "| Item | Status |", "|---|---|",
        "| Real microphone capture and Google speech recognition | NOT RUN - manual test needed |",
        "| Spoken output through Windows SAPI5 voices (pyttsx3) | NOT RUN - manual test needed |",
        "| Real Gmail sending with an App Password | NOT RUN - manual test needed (automated tests use a mocked SMTP server) |",
        "| Live OpenWeatherMap request with a real key | NOT RUN - manual test needed (automated tests use mocked responses) |",
        "| Live Wikipedia lookup | NOT RUN - manual test needed (automated tests use mocked responses) |",
        "| Opening the real default browser | NOT RUN - manual test needed |",
        "| Audible reminder beep (winsound) | NOT RUN - manual test needed |",
        "| setup.bat / run.bat / test.bat / diagnose.bat on Windows | NOT RUN - written for Windows CMD, not executable in the build environment |",
        "| Clean-venv `pip install -r requirements.txt` on Windows | NOT RUN - the build environment had no internet access |",
        "| GUI launch, animation and look and feel | See the GUI rows above: rows marked NOT RUN mean PySide6 was missing here; on your PC they run automatically |",
    ]
    out = ROOT / "docs" / "QA_REPORT.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nQA report written to {out}")
    return 0 if result.wasSuccessful() else 1


if __name__ == "__main__":
    sys.exit(main())
